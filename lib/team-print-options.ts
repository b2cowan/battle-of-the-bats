/**
 * MORE PRINT OPTIONS — the six print settings a Premium team sets inside "How your documents look" (owner rulings A8,
 * C2, C3, 2026-11-20; build prompt docs/projects/active/SETTINGS_BOTH_WORKSPACES_BUILD_PROMPT.md § Session 2).
 *
 * They are the workspace organization's own print settings (`organizations.pdf_settings`) — a standalone workspace holds
 * one team, so they are the team's — saved by the card's one Save look, by the workspace OWNER (A3). They reach every
 * document the workspace prints, its own tournaments' too, because that is where those documents read them.
 *
 * ⚖ C2: SIX rows, not the drawing's seven — "Player notes" is not here, because no printout reads it (a switch that
 * changes nothing). Not carried either (A8): file names (a fixed pattern), the two header lines, the colour and the footer
 * (already in the card), internal admin notes (registration forms).
 *
 * Pure (relative imports only), so a plain Node unit test reads it.
 */
import type { OrgPdfSettings } from './export/pdf';

export type PrintOptions = Pick<OrgPdfSettings,
  'showPageNumbers' | 'showDateStamp' | 'showBranding' | 'orientation' | 'reportDensity' | 'includeGuardianContacts'>;

export const PRINT_OPTION_KEYS = [
  'showPageNumbers', 'showDateStamp', 'showBranding', 'orientation', 'reportDensity', 'includeGuardianContacts',
] as const satisfies readonly (keyof PrintOptions)[];

const SWITCHES = ['showPageNumbers', 'showDateStamp', 'showBranding', 'includeGuardianContacts'] as const;

/** The six values as the paper prints them today (the resolved settings), never the drawing's illustration. */
export function printOptionsOf(settings: PrintOptions): PrintOptions {
  return {
    showPageNumbers: settings.showPageNumbers,
    showDateStamp: settings.showDateStamp,
    showBranding: settings.showBranding,
    orientation: settings.orientation,
    reportDensity: settings.reportDensity,
    includeGuardianContacts: settings.includeGuardianContacts,
  };
}

/** A request's `print` object, checked whole: every one of the six, each its own type — or the words of the refusal. */
export function cleanPrintOptions(raw: unknown): { print: PrintOptions } | { error: string } {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return { error: 'Print options are missing.' };
  const r = raw as Record<string, unknown>;
  for (const k of SWITCHES) {
    if (typeof r[k] !== 'boolean') return { error: 'Print options are missing.' };
  }
  if (r.orientation !== 'portrait' && r.orientation !== 'landscape') return { error: 'Pick Portrait or Landscape.' };
  if (r.reportDensity !== 'readable' && r.reportDensity !== 'compact') return { error: 'Pick Readable or Compact.' };
  return { print: printOptionsOf(r as unknown as PrintOptions) };
}

/** Saved INTO the stored settings: the six keys change, every other key the organization holds stays as it was. */
export function mergePrintOptions(stored: Record<string, unknown> | null | undefined, print: PrintOptions): Record<string, unknown> {
  return { ...(stored ?? {}), ...print };
}

