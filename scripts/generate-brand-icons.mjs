#!/usr/bin/env node
/**
 * generate-brand-icons.mjs — EVERY ICON FILE FROM THE ONE MARK (The public face, warm: S4 Part B; owner ruling W,
 * 2026-10-23: the refined Joined FL, olive leading, lime kept for actions; spec docs/agents/brand/VISUAL_IDENTITY.md §4).
 *
 * The geometry is `lib/brand-mark.ts` (copied from the refinement page, never redrawn). This script draws each file from
 * it, so no icon can carry a second copy of the shape. It replaces the old four-mark system (generate-pwa-icons.js and
 * generate-favicon-ico.js: the "FL / HQ" lettermark and the lime ">" chevron on near-black).
 *
 * ⚠ NEW FILE NAMES ON PURPOSE (`fl-*`): browsers and phones cache an icon by its address, so a redrawn icon under an
 * old name can sit in a tab or on a home screen for months. Renaming makes every cache fetch the new one.
 *
 *   public/brand/fl-mark.svg          the bare mark, olive, no tile (the lockup's mark; the export mark's source)
 *   public/brand/fl-tile.svg          the rounded olive tile, main cut (32 px and up)
 *   public/icons/fl-tab-16.png        the tab icon at 16: the 16 px CUT on the rounded tile (the main cut is mush there)
 *   public/icons/fl-tab-32.png        the tab icon at 32: the main cut on the rounded tile
 *   app/favicon.ico                   16 (16 px cut), 32 and 48 (main cut) — Next serves it as the site favicon
 *   public/icons/fl-apple-180.png     the iPhone icon: a FULL SQUARE (iOS paints transparent corners black)
 *   public/icons/fl-192.png           Android "any" (and the push picture), full square
 *   public/icons/fl-512.png           Android "any", full square
 *   public/icons/fl-512-maskable.png  Android maskable: the glyph at 84% inside the safe circle, full-bleed olive
 *   public/icons/fl-mark-ink-192.png  the export mark: the bare mark in one colour (ink) on transparent, drawn beside the
 *                                     "Generated by FieldLogicHQ" words on an exported PDF or spreadsheet
 *   public/icons/fl-badge-96.png      the push status-bar badge: a WHITE silhouette of the 16 px cut on transparent
 *                                     (Android paints the small icon by alpha only), 96 = 16 × 6, so it stays on the
 *                                     pixel grid and is crisp at 16, 32, 48 and 96
 *
 * On a tile, square or maskable icon the glyph sits 1.5 units right of centre (MARK_TILE_NUDGE_X); the 16 px cut and
 * the bare mark do not.
 *
 * Run: node scripts/generate-brand-icons.mjs        Requires: sharp (devDependency)
 * `tests/unit/public-face-s4-identity.test.ts` checks every file named here exists and is referenced.
 */
import sharp from 'sharp';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  MARK_PATH_MAIN, MARK_PATH_SMALL, MARK_BARE_VIEWBOX, MARK_TILE_NUDGE_X, BRAND_OLIVE, BRAND_PAPER, BRAND_INK,
} from '../lib/brand-mark.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (rel) => { const p = join(ROOT, rel); mkdirSync(dirname(p), { recursive: true }); return p; };

const svg = (inner, viewBox = '0 0 64 64') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="512" height="512">${inner}</svg>`;
const nudged = (d, fill) => `<g transform="translate(${MARK_TILE_NUDGE_X} 0)"><path d="${d}" fill="${fill}"/></g>`;

const SOURCES = {
  bare: svg(`<path d="${MARK_PATH_MAIN}" fill="${BRAND_OLIVE}"/>`, MARK_BARE_VIEWBOX),
  tile: svg(`<rect width="64" height="64" rx="12" fill="${BRAND_OLIVE}"/>${nudged(MARK_PATH_MAIN, BRAND_PAPER)}`),
  tile16: svg(`<rect width="64" height="64" rx="12" fill="${BRAND_OLIVE}"/><path d="${MARK_PATH_SMALL}" fill="${BRAND_PAPER}"/>`),
  square: svg(`<rect width="64" height="64" fill="${BRAND_OLIVE}"/>${nudged(MARK_PATH_MAIN, BRAND_PAPER)}`),
  maskable: svg(`<rect width="64" height="64" fill="${BRAND_OLIVE}"/><g transform="translate(32 32) scale(.84) translate(-32 -32)">${nudged(MARK_PATH_MAIN, BRAND_PAPER)}</g>`),
  badge: svg(`<path d="${MARK_PATH_SMALL}" fill="#FFFFFF"/>`),
  ink: svg(`<path d="${MARK_PATH_MAIN}" fill="${BRAND_INK}"/>`, MARK_BARE_VIEWBOX),
};

/** One PNG from an SVG source. `crisp` renders the pixel-grid cut without smoothing between grid steps. */
async function png(source, size, crisp = false) {
  const density = Math.max(72, Math.ceil((72 * size) / 512) * (crisp ? 4 : 2));
  let img = sharp(Buffer.from(source), { density }).resize(size, size, { fit: 'fill', kernel: crisp ? 'nearest' : 'lanczos3' });
  return img.png().toBuffer();
}

/** A PNG-in-ICO file (every modern browser reads it). */
function ico(entries) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(entries.length, 4);
  const dir = Buffer.alloc(16 * entries.length);
  let offset = 6 + dir.length;
  entries.forEach(({ size, data }, i) => {
    const o = i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, o); dir.writeUInt8(size >= 256 ? 0 : size, o + 1);
    dir.writeUInt8(0, o + 2); dir.writeUInt8(0, o + 3);
    dir.writeUInt16LE(1, o + 4); dir.writeUInt16LE(32, o + 6);
    dir.writeUInt32LE(data.length, o + 8); dir.writeUInt32LE(offset, o + 12);
    offset += data.length;
  });
  return Buffer.concat([header, dir, ...entries.map((e) => e.data)]);
}

async function main() {
  writeFileSync(out('public/brand/fl-mark.svg'), SOURCES.bare.replace(' width="512" height="512"', '') + '\n');
  writeFileSync(out('public/brand/fl-tile.svg'), SOURCES.tile.replace(' width="512" height="512"', '') + '\n');

  const files = [
    ['public/icons/fl-tab-16.png', SOURCES.tile16, 16, true],
    ['public/icons/fl-tab-32.png', SOURCES.tile, 32],
    ['public/icons/fl-apple-180.png', SOURCES.square, 180],
    ['public/icons/fl-192.png', SOURCES.square, 192],
    ['public/icons/fl-512.png', SOURCES.square, 512],
    ['public/icons/fl-512-maskable.png', SOURCES.maskable, 512],
    ['public/icons/fl-badge-96.png', SOURCES.badge, 96, true],
    ['public/icons/fl-mark-ink-192.png', SOURCES.ink, 192],
  ];
  for (const [rel, source, size, crisp] of files) {
    writeFileSync(out(rel), await png(source, size, crisp));
    console.log(`✓ ${rel} (${size}×${size})`);
  }

  const entries = [
    { size: 16, data: await png(SOURCES.tile16, 16, true) },
    { size: 32, data: await png(SOURCES.tile, 32) },
    { size: 48, data: await png(SOURCES.tile, 48) },
  ];
  writeFileSync(out('app/favicon.ico'), ico(entries));
  console.log('✓ app/favicon.ico (16 · 32 · 48)');
}

main().catch((err) => { console.error('Icon generation failed:', err); process.exit(1); });
