-- The common fee-line write. Both tournament receipts and house registrations
-- use this, so the source, audit fields and posted-only rule cannot diverge.
CREATE OR REPLACE FUNCTION public.club_fee_post(
  p_ledger uuid, p_source text, p_source_id uuid, p_day date,
  p_description text, p_amount numeric, p_actor uuid,
  p_category uuid DEFAULT NULL, p_item uuid DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id uuid;
BEGIN
  IF p_amount <= 0 OR p_day IS NULL THEN RAISE EXCEPTION 'A fee needs a positive amount and day'; END IF;
  INSERT INTO accounting_entries(ledger_id, entry_date, description, amount, entry_type, status,
    category, source_module, source_entity_id, created_by, budget_category_id, budget_item_id)
  VALUES(p_ledger, p_day, p_description, p_amount, 'income', 'posted',
    'registration_fee', p_source, p_source_id, p_actor, p_category, p_item)
  RETURNING id INTO v_id;
  RETURN v_id;
END $$;
REVOKE ALL ON FUNCTION public.club_fee_post(uuid,text,uuid,date,text,numeric,uuid,uuid,uuid) FROM PUBLIC, anon, authenticated;
