-- A paid figure is cumulative. A higher figure writes only the increase.
-- Reductions void affected receipt lines; a partial correction replaces a
-- line with the corrected amount and retains both versions in the audit trail.
CREATE OR REPLACE FUNCTION public.club_tournament_fee_reconcile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_t public.tournaments%ROWTYPE; v_org public.organizations%ROWTYPE;
  v_paid numeric(12,2); v_booked numeric(12,2); v_diff numeric(12,2);
  v_book uuid; v_cat uuid; v_item uuid; v_entry uuid; v_receipt uuid;
  v_row record; v_other numeric(12,2); v_keep numeric(12,2); v_new uuid;
  v_day date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  SELECT * INTO v_t FROM tournaments WHERE id=NEW.tournament_id;
  SELECT * INTO v_org FROM organizations WHERE id=v_t.org_id;
  IF current_setting('app.club_fee_shared', true)='on' THEN RETURN NEW; END IF;
  IF NOT (v_org.plan_id IN ('club','club_large') OR coalesce(v_org.enabled_addons, '[]'::jsonb) ? 'module_accounting')
     OR v_t.settings->>'fee_scope' = 'free' THEN RETURN NEW; END IF;
  IF EXISTS (SELECT 1 FROM rep_team_tournament_registrations l JOIN rep_teams r ON r.id=l.rep_team_id
             WHERE l.tournament_team_id=NEW.id AND l.org_id=v_t.org_id AND r.org_id=v_t.org_id) THEN RETURN NEW; END IF;

  v_paid := greatest(coalesce(NEW.total_paid,0), coalesce(NEW.deposit_paid,0), 0);
  SELECT coalesce(sum(a.amount),0) INTO v_booked
    FROM tournament_fee_receipt_allocations a
    JOIN tournament_fee_receipts r ON r.id=a.receipt_id
    JOIN accounting_entries e ON e.id=r.entry_id
    WHERE a.team_id=NEW.id AND e.status='posted';
  v_diff := v_paid - NEW.fee_book_baseline - v_booked;
  IF v_diff = 0 THEN RETURN NEW; END IF;
  IF v_diff > 0 THEN
    SELECT category_id, item_id INTO v_cat, v_item FROM club_tournament_fee_word(NEW.tournament_id);
    v_book := club_tournament_ledger(NEW.tournament_id);
    v_receipt := gen_random_uuid();
    v_entry := club_fee_post(v_book, 'tournament_fee_receipt', v_receipt, v_day,
      NEW.name || ' — entry fee', v_diff, NEW.fee_changed_by, v_cat, v_item);
    INSERT INTO tournament_fee_receipts(id,tournament_id,entry_id) VALUES(v_receipt,NEW.tournament_id,v_entry);
    INSERT INTO tournament_fee_receipt_allocations(receipt_id,team_id,amount) VALUES(v_receipt,NEW.id,v_diff);
  ELSE
    FOR v_row IN
      SELECT a.receipt_id, a.amount, r.entry_id, e.ledger_id, e.entry_date,
             e.budget_category_id, e.budget_item_id, e.description
      FROM tournament_fee_receipt_allocations a
      JOIN tournament_fee_receipts r ON r.id=a.receipt_id
      JOIN accounting_entries e ON e.id=r.entry_id
      WHERE a.team_id=NEW.id AND e.status='posted' ORDER BY r.ordinal DESC
    LOOP
      EXIT WHEN v_diff >= 0;
      v_keep := greatest(0, v_row.amount + v_diff);
      -- Lock the line first. Two corrections on teams that share one transfer both try to void and replace it; the
      -- second waits here, finds it already void, and leaves it (never a second replacement built from stale shares).
      PERFORM 1 FROM accounting_entries WHERE id=v_row.entry_id AND status='posted' FOR UPDATE;
      IF NOT FOUND THEN v_diff := 0; EXIT; END IF;
      PERFORM club_fee_void(v_row.entry_id, NEW.fee_changed_by, 'Payment corrected or undone');
      v_diff := v_diff + v_row.amount - v_keep;
      -- A shared receipt may still contain money belonging to another team.
      SELECT coalesce(sum(amount),0) INTO v_other FROM tournament_fee_receipt_allocations
        WHERE receipt_id=v_row.receipt_id AND team_id<>NEW.id;
      IF v_other+v_keep > 0 THEN
        v_receipt := gen_random_uuid();
        v_new := club_fee_post(v_row.ledger_id, 'tournament_fee_receipt', v_receipt, v_day,
          v_row.description, v_other+v_keep, NEW.fee_changed_by,
          v_row.budget_category_id, v_row.budget_item_id);
        INSERT INTO tournament_fee_receipts(id,tournament_id,entry_id) VALUES(v_receipt,NEW.tournament_id,v_new);
        INSERT INTO tournament_fee_receipt_allocations(receipt_id,team_id,amount)
          SELECT v_receipt, team_id, CASE WHEN team_id=NEW.id THEN v_keep ELSE amount END
          FROM tournament_fee_receipt_allocations WHERE receipt_id=v_row.receipt_id
          AND (team_id<>NEW.id OR v_keep>0);
      END IF;
    END LOOP;
    IF v_diff < 0 THEN
      UPDATE teams SET fee_book_baseline=greatest(0, NEW.fee_book_baseline+v_diff) WHERE id=NEW.id;
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.club_tournament_fee_before()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
DECLARE v_t public.tournaments%ROWTYPE; v_org public.organizations%ROWTYPE; v_fee numeric(12,2);
BEGIN
  SELECT * INTO v_t FROM tournaments WHERE id=NEW.tournament_id;
  SELECT * INTO v_org FROM organizations WHERE id=v_t.org_id;
  IF NOT (v_org.plan_id IN ('club','club_large') OR coalesce(v_org.enabled_addons,'[]'::jsonb) ? 'module_accounting')
     OR v_t.settings->>'fee_scope'='free' THEN RETURN NEW; END IF;
  IF TG_OP='UPDATE' AND NEW.payment_status='pending' AND OLD.payment_status='paid'
     AND NEW.total_paid IS NOT DISTINCT FROM OLD.total_paid
     AND NEW.deposit_paid IS NOT DISTINCT FROM OLD.deposit_paid THEN
    NEW.total_paid := 0; NEW.deposit_paid := 0;
  END IF;
  -- The fee is filled in when a team BECOMES paid with no amount, never on a row that was already paid: an import that
  -- re-sends "paid" for an old status-only row, or an admin taking a paid team's amounts back to 0, must not post
  -- income for money the book never saw.
  IF NEW.payment_status='paid' AND (TG_OP='INSERT' OR OLD.payment_status IS DISTINCT FROM 'paid')
     AND greatest(coalesce(NEW.total_paid,0),coalesce(NEW.deposit_paid,0))=0 THEN
    IF v_t.fee_schedule_mode='division' OR v_t.settings->>'fee_scope'='allow_override' THEN
      SELECT total_fee_amount INTO v_fee FROM divisions WHERE id=NEW.division_id;
    END IF;
    NEW.total_paid := coalesce(v_fee,v_t.total_fee_amount,0);
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS teams_club_fee_before ON public.teams;
CREATE TRIGGER teams_club_fee_before BEFORE INSERT OR UPDATE OF payment_status,total_paid,deposit_paid ON public.teams
FOR EACH ROW EXECUTE FUNCTION public.club_tournament_fee_before();
DROP TRIGGER IF EXISTS teams_club_fee_reconcile ON public.teams;
CREATE TRIGGER teams_club_fee_reconcile AFTER INSERT OR UPDATE OF payment_status,total_paid,deposit_paid ON public.teams
FOR EACH ROW EXECUTE FUNCTION public.club_tournament_fee_reconcile();

-- Identity changes cannot silently change the financial meaning of a paid row.
-- Serialize with payment writes through the registration row lock.
CREATE OR REPLACE FUNCTION public.club_tournament_own_link_guard()
RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
DECLARE v_team public.teams%ROWTYPE; v_host uuid;
BEGIN
  SELECT * INTO v_team FROM teams
    WHERE id=CASE WHEN TG_OP='DELETE' THEN OLD.tournament_team_id ELSE NEW.tournament_team_id END
    FOR UPDATE;
  IF NOT FOUND THEN RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END; END IF;
  SELECT org_id INTO v_host FROM tournaments WHERE id=v_team.tournament_id;
  IF TG_OP='DELETE' THEN
    IF OLD.org_id=v_host AND EXISTS(SELECT 1 FROM rep_teams WHERE id=OLD.rep_team_id AND org_id=v_host)
       AND greatest(coalesce(v_team.total_paid,0),coalesce(v_team.deposit_paid,0))>0 THEN
      RAISE EXCEPTION 'Undo this team''s paid status before removing its club-team link';
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.org_id<>v_host OR NOT EXISTS(SELECT 1 FROM rep_teams WHERE id=NEW.rep_team_id AND org_id=v_host) THEN
    RAISE EXCEPTION 'The rep team and tournament must belong to the same club';
  END IF;
  IF EXISTS(SELECT 1 FROM tournament_fee_receipt_allocations a
      JOIN tournament_fee_receipts r ON r.id=a.receipt_id
      JOIN accounting_entries e ON e.id=r.entry_id
      WHERE a.team_id=v_team.id AND e.status='posted') THEN
    RAISE EXCEPTION 'Undo the recorded entry fee before linking this as our team';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS rep_team_tournament_fee_guard ON public.rep_team_tournament_registrations;
CREATE TRIGGER rep_team_tournament_fee_guard
BEFORE INSERT OR UPDATE OF rep_team_id,org_id,tournament_team_id OR DELETE
ON public.rep_team_tournament_registrations
FOR EACH ROW EXECUTE FUNCTION public.club_tournament_own_link_guard();

-- An explicit one-transfer action can cover several teams. It holds and updates
-- all team rows, suppresses the per-team receipt trigger for this transaction,
-- then posts exactly one line with one allocation per team.
CREATE OR REPLACE FUNCTION public.club_tournament_shared_payment(
  p_tournament uuid, p_team_ids uuid[], p_amounts numeric[], p_actor uuid, p_day date,
  p_method text DEFAULT NULL, p_reference text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_t public.tournaments%ROWTYPE; v_org public.organizations%ROWTYPE;
  v_team public.teams%ROWTYPE; v_i integer; v_fee numeric; v_next numeric;
  v_total numeric(12,2):=0; v_receipt uuid:=gen_random_uuid();
  v_entry uuid; v_book uuid; v_cat uuid; v_item uuid; v_names text;
BEGIN
  IF cardinality(p_team_ids)<2 OR cardinality(p_team_ids)<>cardinality(p_amounts)
     OR cardinality(p_team_ids)<>cardinality(ARRAY(SELECT DISTINCT unnest(p_team_ids))) THEN
    RAISE EXCEPTION 'Choose at least two different teams and an amount for each';
  END IF;
  SELECT * INTO v_t FROM tournaments WHERE id=p_tournament;
  SELECT * INTO v_org FROM organizations WHERE id=v_t.org_id;
  IF NOT (v_org.plan_id IN ('club','club_large') OR coalesce(v_org.enabled_addons,'[]'::jsonb) ? 'module_accounting')
     OR v_t.settings->>'fee_scope'='free' THEN RAISE EXCEPTION 'This tournament does not record fees in Accounting'; END IF;
  IF p_method IS NOT NULL AND p_method NOT IN ('etransfer','cash','cheque','card','other') THEN
    RAISE EXCEPTION 'Invalid payment method'; END IF;
  -- Consistent lock order prevents two overlapping transfers from deadlocking.
  PERFORM 1 FROM teams WHERE id=ANY(p_team_ids) AND tournament_id=p_tournament ORDER BY id FOR UPDATE;
  IF NOT FOUND OR (SELECT count(*) FROM teams WHERE id=ANY(p_team_ids) AND tournament_id=p_tournament)<>cardinality(p_team_ids)
    THEN RAISE EXCEPTION 'A selected team is not in this tournament'; END IF;
  PERFORM set_config('app.club_fee_shared','on',true);
  FOR v_i IN 1..cardinality(p_team_ids) LOOP
    SELECT * INTO v_team FROM teams WHERE id=p_team_ids[v_i];
    IF p_amounts[v_i] IS NULL OR p_amounts[v_i]<=0 THEN RAISE EXCEPTION 'Every payment amount must be positive'; END IF;
    IF EXISTS(SELECT 1 FROM rep_team_tournament_registrations l JOIN rep_teams r ON r.id=l.rep_team_id
      WHERE l.tournament_team_id=v_team.id AND l.org_id=v_t.org_id AND r.org_id=v_t.org_id) THEN
      RAISE EXCEPTION 'Our team has no entry fee'; END IF;
    v_next := greatest(coalesce(v_team.total_paid,0),coalesce(v_team.deposit_paid,0))+p_amounts[v_i];
    v_fee := v_t.total_fee_amount;
    IF v_t.fee_schedule_mode='division' OR v_t.settings->>'fee_scope'='allow_override' THEN
      SELECT total_fee_amount INTO v_fee FROM divisions WHERE id=v_team.division_id;
    END IF;
    UPDATE teams SET total_paid=v_next, payment_status=CASE WHEN v_fee IS NOT NULL AND v_next>=v_fee THEN 'paid' ELSE payment_status END,
      fee_changed_by=p_actor, payment_collected_at=now() WHERE id=v_team.id;
    v_total := v_total+p_amounts[v_i];
  END LOOP;
  PERFORM set_config('app.club_fee_shared','off',true);
  SELECT string_agg(name, ', ' ORDER BY name) INTO v_names FROM teams WHERE id=ANY(p_team_ids);
  SELECT category_id,item_id INTO v_cat,v_item FROM club_tournament_fee_word(p_tournament);
  v_book := club_tournament_ledger(p_tournament);
  v_entry := club_fee_post(v_book,'tournament_fee_receipt',v_receipt,p_day,
    left(v_names,180) || ' — one entry-fee payment',v_total,p_actor,v_cat,v_item);
  UPDATE accounting_entries SET payment_method=p_method,notes=left(p_reference,500) WHERE id=v_entry;
  INSERT INTO tournament_fee_receipts(id,tournament_id,entry_id) VALUES(v_receipt,p_tournament,v_entry);
  FOR v_i IN 1..cardinality(p_team_ids) LOOP
    INSERT INTO tournament_fee_receipt_allocations(receipt_id,team_id,amount)
      VALUES(v_receipt,p_team_ids[v_i],p_amounts[v_i]);
  END LOOP;
  RETURN v_receipt;
END $$;
