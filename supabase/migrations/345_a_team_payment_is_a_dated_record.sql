-- 345: a team's payment is a dated record, and each one is one ledger line.
-- Plan: docs/projects/active/TEAM_PAYMENTS_LIST_PLAN.md (drawn and ruled 2026-10-21; the four calls taken as recommended).
--
-- Until now a team carried two typed running totals (teams.deposit_paid / total_paid) and an AFTER trigger diffed them into the
-- club's tournament book (mig 342). Typing 109 made three lines, every line was dated "today", and the two totals meant different
-- things to different readers. A payment is now a row: an amount, the date it arrived, a label, how it arrived. The ledger line is
-- written by the same function that writes the row, dated the day it arrived.
--
-- teams.total_paid / deposit_paid / payment_status / payment_collected_at stay, as a CACHE the functions below keep current in
-- the same transaction. Every reader keeps reading them:
--   total_paid   = the sum of the team's posted payments
--   deposit_paid = least(that sum, the deposit fee), 0 with no deposit
--   payment_status = 'paid' when the sum reaches the fee; back to 'pending' when payments the team was paid BY now fall short.
--                    A legacy team marked paid with no (or too few) payments is left as marked until money completes it.
--   payment_collected_at = the day the payment that completed the fee arrived; cleared when the team stops being paid
-- NOTHING ELSE WRITES THE TWO FIGURES (total_paid, deposit_paid) any more: tests/unit/team-payments-guard.test.ts fails the build
-- if app code does. A status-only "paid" remains for a team with no fee schedule and for the club's own team (nothing is owed).
-- A fee edit refreshes the figures of the teams that have payments (section 5b): the deposit cap depends on the fee.
--
-- Retired here: the two triggers that diffed the figures (and their functions). Left in place, unused, for a later release
-- (a table or column is never dropped in the release that stops using it): fee_book_baseline, tournament_fee_receipts,
-- tournament_fee_receipt_allocations.
--
-- ⚠ The old triggers are dropped BEFORE the backfill: the backfill rewrites every paid team's figures, and 342's reconcile trigger
-- (UPDATE OF those columns) would fire on each and could post the whole figure as a new ledger line on a club with Accounting.
--
-- ⚠ LOCK ORDER everywhere: tournament row (club_tournament_fee_word) → team rows (in id order) → the ledger line. A payment row
-- is inserted only after the first two, never before: its foreign key takes a share lock on the tournament row, and taking the
-- update lock after a share lock is how two payments on one tournament would deadlock.
--
-- Apply before the matching application code. Backfill below turns what is already recorded into rows; it halts (the whole
-- migration rolls back) if any team's rows would not add up to the figure it carries today.
BEGIN;

