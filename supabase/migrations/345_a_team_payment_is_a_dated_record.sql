-- ── 2. Small helpers ────────────────────────────────────────────────────────────────────────────
-- Does this tournament's fee money post to a book? The same test mig 342 made: a club plan or the accounting add-on, and an
-- event that is not "free". Decided when a payment is recorded; adding Accounting later posts nothing retroactively.
CREATE OR REPLACE FUNCTION public.tournament_fee_book_on(p_tournament uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT coalesce(
    (o.plan_id IN ('club', 'club_large') OR coalesce(o.enabled_addons, '[]'::jsonb) ? 'module_accounting')
    AND coalesce(t.settings->>'fee_scope', '') <> 'free', false)
  FROM tournaments t JOIN organizations o ON o.id = t.org_id
  WHERE t.id = p_tournament
$$;

-- The fee that applies to a team: its division's in division mode (when the division states one), else the event's.
-- Mirrors lib/mark-paid.ts effectiveFee. A fee of 0 is no fee.
CREATE OR REPLACE FUNCTION public.tournament_team_fee(p_team uuid)
RETURNS TABLE(total numeric, deposit numeric) LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT
    nullif(CASE WHEN tr.fee_schedule_mode = 'division' AND d.total_fee_amount IS NOT NULL THEN d.total_fee_amount ELSE tr.total_fee_amount END, 0),
    CASE WHEN tr.fee_schedule_mode = 'division' AND d.total_fee_amount IS NOT NULL THEN d.deposit_amount ELSE tr.deposit_amount END
  FROM teams t
  JOIN tournaments tr ON tr.id = t.tournament_id
  LEFT JOIN divisions d ON d.id = t.division_id
  WHERE t.id = p_team
$$;

-- What the ledger line says: one team is "<name> — entry fee" (with "(deposit)" or "(balance)" for a lone labelled payment);
-- several teams on one transfer are "<names> — one entry-fee payment".
CREATE OR REPLACE FUNCTION public.tournament_payment_words(p_payments uuid[])
RETURNS text LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE v_n integer; v_teams integer; v_name text; v_label text; v_names text;
BEGIN
  SELECT count(*), count(DISTINCT p.team_id) INTO v_n, v_teams FROM tournament_team_payments p WHERE p.id = ANY(p_payments);
  IF v_n = 0 THEN RETURN NULL; END IF;
  IF v_teams = 1 THEN
    SELECT t.name, (array_agg(p.label ORDER BY p.ordinal))[1] INTO v_name, v_label
    FROM tournament_team_payments p JOIN teams t ON t.id = p.team_id WHERE p.id = ANY(p_payments) GROUP BY t.name;
    RETURN v_name || ' — entry fee' || CASE WHEN v_n = 1 AND v_label IN ('Deposit', 'Balance') THEN ' (' || lower(v_label) || ')' ELSE '' END;
  END IF;
  SELECT string_agg(s.name, ', ' ORDER BY s.name) INTO v_names
  FROM (SELECT DISTINCT t.name FROM tournament_team_payments p JOIN teams t ON t.id = p.team_id WHERE p.id = ANY(p_payments)) s;
  RETURN left(v_names, 180) || ' — one entry-fee payment';
END $$;

-- ── 3. The cache: the ONLY writer of the paid figures ───────────────────────────────────────────
-- The caller holds the team row (SELECT … FOR UPDATE). p_mode 'live' lets the status move; 'backfill' writes the two figures
-- only and leaves the status and the collected stamp alone. p_completed_on is kept for the callers' signature and is no longer
-- read: the collected day is worked out from the payments themselves (the one whose running total first reaches the fee).
CREATE OR REPLACE FUNCTION public.team_payments_refresh(p_team uuid, p_actor uuid, p_mode text DEFAULT 'live', p_completed_on date DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_team public.teams%ROWTYPE; v_fee_total numeric; v_fee_dep numeric; v_sum numeric(12,2); v_dep numeric(12,2);
  v_status text; v_became_paid boolean := false; v_became_unpaid boolean := false; v_collected timestamptz; v_day date;
  v_today date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  SELECT * INTO v_team FROM teams WHERE id = p_team;
  IF NOT FOUND THEN RAISE EXCEPTION 'Team not found'; END IF;
  SELECT f.total, f.deposit INTO v_fee_total, v_fee_dep FROM tournament_team_fee(p_team) f;
  SELECT coalesce(sum(amount), 0) INTO v_sum FROM tournament_team_payments WHERE team_id = p_team AND status = 'posted';
  v_dep := CASE WHEN v_fee_dep IS NULL THEN 0 ELSE least(v_sum, v_fee_dep) END;
  v_status := v_team.payment_status;
  v_collected := v_team.payment_collected_at;
  IF p_mode = 'live' AND v_fee_total IS NOT NULL THEN
    IF v_sum >= v_fee_total THEN
      v_status := 'paid';
      IF v_team.payment_status IS DISTINCT FROM 'paid' THEN v_became_paid := true; END IF;
      -- The day the payment that completed the fee arrived (an undated "Earlier payment" completing it leaves the stamp alone).
      SELECT r.d INTO v_day FROM (
        SELECT paid_on AS d, sum(amount) OVER (ORDER BY coalesce(paid_on, date '1900-01-01'), ordinal) AS running
        FROM tournament_team_payments WHERE team_id = p_team AND status = 'posted'
      ) r WHERE r.running >= v_fee_total ORDER BY r.running LIMIT 1;
      IF v_day IS NOT NULL AND (v_collected IS NULL OR (v_collected AT TIME ZONE 'America/Toronto')::date <> v_day) THEN
        v_collected := CASE WHEN v_day >= v_today THEN now() ELSE ((v_day + time '12:00') AT TIME ZONE 'America/Toronto') END;
      END IF;
    ELSIF v_team.payment_status = 'paid' AND v_team.total_paid >= v_fee_total THEN
      -- Paid BY these payments, and now short of the fee. (A legacy team marked paid with too little recorded is left as
      -- marked: this change did not make it unpaid.)
      v_status := 'pending'; v_became_unpaid := true; v_collected := NULL;
    END IF;
  END IF;
  UPDATE teams SET total_paid = v_sum, deposit_paid = v_dep, payment_status = v_status,
    payment_collected_at = v_collected, fee_changed_by = coalesce(p_actor, fee_changed_by)
  WHERE id = p_team;
  RETURN jsonb_build_object('total', v_sum, 'deposit', v_dep, 'status', v_status, 'feeTotal', v_fee_total,
    'becamePaid', v_became_paid, 'becameUnpaid', v_became_unpaid);
END $$;

-- ── 4. Record, change, remove ───────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.tournament_team_payment_record(
  p_team uuid, p_amount numeric, p_paid_on date, p_label text, p_method text, p_actor uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_team public.teams%ROWTYPE; v_t public.tournaments%ROWTYPE; v_id uuid := gen_random_uuid(); v_amt numeric(12,2) := round(p_amount, 2);
  v_label text; v_book uuid; v_cat uuid; v_item uuid; v_entry uuid; v_refresh jsonb;
  v_today date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  IF v_amt IS NULL OR v_amt <= 0 OR v_amt > 1000000 THEN RAISE EXCEPTION 'Enter an amount above $0.'; END IF;
  IF p_paid_on IS NULL THEN RAISE EXCEPTION 'Choose the date the payment arrived.'; END IF;
  IF p_paid_on > v_today THEN RAISE EXCEPTION 'A payment can’t be dated in the future.'; END IF;
  IF p_method IS NOT NULL AND p_method NOT IN ('etransfer', 'cash', 'cheque', 'card', 'other') THEN RAISE EXCEPTION 'Invalid payment method'; END IF;
  SELECT * INTO v_team FROM teams WHERE id = p_team;
  IF NOT FOUND THEN RAISE EXCEPTION 'Team not found'; END IF;
  SELECT * INTO v_t FROM tournaments WHERE id = v_team.tournament_id;
  v_label := CASE WHEN p_label IN ('Deposit', 'Balance', 'Entry fee', 'Payment', 'Imported payment') THEN p_label ELSE 'Payment' END;
  -- Lock order: the tournament row first (the event's words and book), then the team, THEN the payment row.
  IF tournament_fee_book_on(v_team.tournament_id) THEN
    SELECT w.category_id, w.item_id INTO v_cat, v_item FROM club_tournament_fee_word(v_team.tournament_id) w;
    v_book := club_tournament_ledger(v_team.tournament_id);
  END IF;
  SELECT * INTO v_team FROM teams WHERE id = p_team FOR UPDATE;
  IF EXISTS (SELECT 1 FROM rep_team_tournament_registrations l JOIN rep_teams r ON r.id = l.rep_team_id
             WHERE l.tournament_team_id = v_team.id AND l.org_id = v_t.org_id AND r.org_id = v_t.org_id) THEN
    RAISE EXCEPTION 'Our team has no entry fee';
  END IF;
  INSERT INTO tournament_team_payments(id, team_id, tournament_id, org_id, amount, paid_on, label, method, created_by)
  VALUES(v_id, v_team.id, v_team.tournament_id, v_t.org_id, v_amt, p_paid_on, v_label, p_method, p_actor);
  IF v_book IS NOT NULL THEN
    v_entry := club_fee_post(v_book, 'tournament_fee_receipt', v_id, p_paid_on, tournament_payment_words(ARRAY[v_id]),
      v_amt, p_actor, v_cat, v_item);
    IF p_method IS NOT NULL THEN UPDATE accounting_entries SET payment_method = p_method WHERE id = v_entry; END IF;
    UPDATE tournament_team_payments SET entry_id = v_entry WHERE id = v_id;
  END IF;
  v_refresh := team_payments_refresh(v_team.id, p_actor, 'live', p_paid_on);
  RETURN v_refresh || jsonb_build_object('paymentId', v_id, 'entryId', v_entry);
END $$;

-- "Mark paid" and "Deposit paid" for a team: record what is still due, dated today, in one locked step so two presses make
-- one payment. p_scope 'all' = the rest of the fee; 'deposit' = the rest of the deposit. A team with no fee records nothing.
CREATE OR REPLACE FUNCTION public.tournament_team_payment_pay_due(p_team uuid, p_actor uuid, p_scope text, p_label text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_team public.teams%ROWTYPE; v_fee_total numeric; v_fee_dep numeric; v_sum numeric; v_amount numeric; v_label text;
  v_today date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  IF p_scope NOT IN ('all', 'deposit') THEN RAISE EXCEPTION 'Unknown payment scope'; END IF;
  SELECT * INTO v_team FROM teams WHERE id = p_team;
  IF NOT FOUND THEN RAISE EXCEPTION 'Team not found'; END IF;
  -- The tournament's lock comes first (see the note at the top), exactly as record() takes it, then the team: two presses
  -- still serialise on the team, and a press cannot deadlock with a record on the same team.
  IF tournament_fee_book_on(v_team.tournament_id) THEN PERFORM club_tournament_fee_word(v_team.tournament_id); END IF;
  SELECT * INTO v_team FROM teams WHERE id = p_team FOR UPDATE;
  SELECT f.total, f.deposit INTO v_fee_total, v_fee_dep FROM tournament_team_fee(p_team) f;
  IF v_fee_total IS NULL THEN RETURN jsonb_build_object('recorded', false, 'noFee', true); END IF;
  SELECT coalesce(sum(amount), 0) INTO v_sum FROM tournament_team_payments WHERE team_id = p_team AND status = 'posted';
  IF p_scope = 'deposit' THEN
    IF v_fee_dep IS NULL THEN RETURN jsonb_build_object('recorded', false, 'total', v_sum); END IF;
    v_amount := least(v_fee_dep, v_fee_total) - v_sum; v_label := 'Deposit';
  ELSE
    v_amount := v_fee_total - v_sum; v_label := 'Payment';
  END IF;
  IF v_amount <= 0 THEN
    -- Nothing is due: the sum already covers it. A team whose status still reads pending (a fee lowered after it paid, an old
    -- typed total) is brought in line with its payments, so "Mark paid" never silently does nothing.
    RETURN team_payments_refresh(p_team, p_actor, 'live', NULL) || jsonb_build_object('recorded', false);
  END IF;
  RETURN tournament_team_payment_record(p_team, v_amount, v_today, coalesce(p_label, v_label), NULL, p_actor) || jsonb_build_object('recorded', true);
END $$;

CREATE OR REPLACE FUNCTION public.tournament_team_payment_change(
  p_payment uuid, p_amount numeric, p_paid_on date, p_method text, p_actor uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_pay public.tournament_team_payments%ROWTYPE; v_old public.accounting_entries%ROWTYPE; v_new uuid; v_ids uuid[]; v_sum numeric;
  v_teams uuid[]; v_refresh jsonb; v_amt numeric(12,2) := round(p_amount, 2); r record;
  v_today date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  IF v_amt IS NULL OR v_amt <= 0 OR v_amt > 1000000 THEN RAISE EXCEPTION 'Enter an amount above $0.'; END IF;
  IF p_paid_on IS NULL THEN RAISE EXCEPTION 'Choose the date the payment arrived.'; END IF;
  IF p_paid_on > v_today THEN RAISE EXCEPTION 'A payment can’t be dated in the future.'; END IF;
  IF p_method IS NOT NULL AND p_method NOT IN ('etransfer', 'cash', 'cheque', 'card', 'other') THEN RAISE EXCEPTION 'Invalid payment method'; END IF;
  -- Hold everything the change touches, then check it is still the same line: every team on the transfer (id order), then the
  -- ledger line. Another change may have replaced the line while this one waited, so the read repeats until it is stable.
  LOOP
    SELECT * INTO v_pay FROM tournament_team_payments WHERE id = p_payment;
    IF NOT FOUND OR v_pay.status <> 'posted' THEN RAISE EXCEPTION 'That payment is no longer recorded.'; END IF;
    SELECT coalesce(array_agg(DISTINCT team_id), ARRAY[]::uuid[]) INTO v_teams
      FROM tournament_team_payments WHERE v_pay.entry_id IS NOT NULL AND entry_id = v_pay.entry_id AND status = 'posted';
    IF NOT (v_pay.team_id = ANY(v_teams)) THEN v_teams := v_teams || v_pay.team_id; END IF;
    PERFORM 1 FROM teams WHERE id = ANY(v_teams) ORDER BY id FOR UPDATE;
    IF v_pay.entry_id IS NOT NULL THEN SELECT * INTO v_old FROM accounting_entries WHERE id = v_pay.entry_id FOR UPDATE; END IF;
    PERFORM 1 FROM tournament_team_payments WHERE id = p_payment AND status = 'posted' AND entry_id IS NOT DISTINCT FROM v_pay.entry_id;
    EXIT WHEN FOUND;
  END LOOP;
  UPDATE tournament_team_payments SET amount = v_amt, paid_on = p_paid_on, method = p_method, updated_at = now() WHERE id = p_payment;
  IF v_pay.entry_id IS NOT NULL AND v_old.status = 'posted' THEN
    -- A line is never edited in place: it is voided and a corrected one posted, so the book keeps both. One transfer has one
    -- date and one way it arrived, so the other teams' rows on it move with it.
    UPDATE tournament_team_payments SET paid_on = p_paid_on, method = p_method, updated_at = now()
    WHERE entry_id = v_pay.entry_id AND status = 'posted' AND id <> p_payment;
    SELECT array_agg(id ORDER BY ordinal), coalesce(sum(amount), 0) INTO v_ids, v_sum
      FROM tournament_team_payments WHERE entry_id = v_pay.entry_id AND status = 'posted';
    PERFORM club_fee_void(v_old.id, p_actor, 'Payment corrected');
    v_new := club_fee_post(v_old.ledger_id, 'tournament_fee_receipt', v_ids[1], p_paid_on, tournament_payment_words(v_ids), v_sum,
      p_actor, v_old.budget_category_id, v_old.budget_item_id);
    UPDATE accounting_entries SET payment_method = p_method, notes = v_old.notes WHERE id = v_new;
    UPDATE tournament_team_payments SET entry_id = v_new WHERE id = ANY(v_ids);
  END IF;
  v_refresh := team_payments_refresh(v_pay.team_id, p_actor, 'live', p_paid_on);
  -- The other teams on a shared transfer: their payment date moved, so their collected day may have too.
  FOR r IN SELECT t AS team_id FROM unnest(v_teams) t WHERE t <> v_pay.team_id LOOP
    PERFORM team_payments_refresh(r.team_id, p_actor, 'live', p_paid_on);
  END LOOP;
  RETURN v_refresh || jsonb_build_object('paymentId', p_payment);
END $$;

CREATE OR REPLACE FUNCTION public.tournament_team_payment_remove(p_payment uuid, p_actor uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_pay public.tournament_team_payments%ROWTYPE; v_old public.accounting_entries%ROWTYPE; v_new uuid; v_ids uuid[]; v_sum numeric;
  v_refresh jsonb;
BEGIN
  -- Hold the team, then the ledger line, and check the payment still points at that line (another change may have replaced it
  -- while this one waited): the read repeats until it is stable.
  LOOP
    SELECT * INTO v_pay FROM tournament_team_payments WHERE id = p_payment;
    IF NOT FOUND THEN RAISE EXCEPTION 'That payment is no longer recorded.'; END IF;
    PERFORM 1 FROM teams WHERE id = v_pay.team_id FOR UPDATE;
    IF v_pay.entry_id IS NOT NULL THEN SELECT * INTO v_old FROM accounting_entries WHERE id = v_pay.entry_id FOR UPDATE; END IF;
    PERFORM 1 FROM tournament_team_payments WHERE id = p_payment AND entry_id IS NOT DISTINCT FROM v_pay.entry_id;
    EXIT WHEN FOUND;
  END LOOP;
  IF v_pay.status <> 'posted' THEN
    RETURN jsonb_build_object('removed', false, 'becameUnpaid', false);
  END IF;
  UPDATE tournament_team_payments SET status = 'removed', removed_at = now(), removed_by = p_actor, updated_at = now() WHERE id = p_payment;
  IF v_pay.entry_id IS NOT NULL AND v_old.status = 'posted' THEN
    PERFORM club_fee_void(v_old.id, p_actor, 'Payment removed');
    SELECT array_agg(id ORDER BY ordinal), coalesce(sum(amount), 0) INTO v_ids, v_sum
      FROM tournament_team_payments WHERE entry_id = v_pay.entry_id AND status = 'posted';
    -- A transfer that covered other teams keeps their share as one corrected line.
    IF v_ids IS NOT NULL AND v_sum > 0 THEN
      v_new := club_fee_post(v_old.ledger_id, 'tournament_fee_receipt', v_ids[1], v_old.entry_date, tournament_payment_words(v_ids), v_sum,
        p_actor, v_old.budget_category_id, v_old.budget_item_id);
      UPDATE accounting_entries SET payment_method = v_old.payment_method, notes = v_old.notes WHERE id = v_new;
      UPDATE tournament_team_payments SET entry_id = v_new WHERE id = ANY(v_ids);
    END IF;
  END IF;
  v_refresh := team_payments_refresh(v_pay.team_id, p_actor, 'live', NULL);
  RETURN v_refresh || jsonb_build_object('removed', true, 'paymentId', p_payment);
END $$;

-- One transfer for several teams: one ledger line, one payment row per team sharing it. Same signature as mig 342's, so the route
-- that calls it is unchanged. The suppress switch of the old trigger is gone with the trigger.
CREATE OR REPLACE FUNCTION public.club_tournament_shared_payment(
  p_tournament uuid, p_team_ids uuid[], p_amounts numeric[], p_actor uuid, p_day date,
  p_method text DEFAULT NULL, p_reference text DEFAULT NULL
) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_t public.tournaments%ROWTYPE; v_team public.teams%ROWTYPE; v_i integer; v_ids uuid[] := ARRAY[]::uuid[]; v_pid uuid;
  v_total numeric(12,2) := 0; v_entry uuid; v_book uuid; v_cat uuid; v_item uuid; v_first uuid; v_amt numeric(12,2);
  v_today date := (now() AT TIME ZONE 'America/Toronto')::date;
BEGIN
  IF cardinality(p_team_ids) < 2 OR cardinality(p_team_ids) <> cardinality(p_amounts)
     OR cardinality(p_team_ids) <> cardinality(ARRAY(SELECT DISTINCT unnest(p_team_ids))) THEN
    RAISE EXCEPTION 'Choose at least two different teams and an amount for each';
  END IF;
  SELECT * INTO v_t FROM tournaments WHERE id = p_tournament;
  IF NOT FOUND THEN RAISE EXCEPTION 'Tournament not found'; END IF;
  IF NOT tournament_fee_book_on(p_tournament) THEN RAISE EXCEPTION 'This tournament does not record fees in Accounting'; END IF;
  IF p_method IS NOT NULL AND p_method NOT IN ('etransfer', 'cash', 'cheque', 'card', 'other') THEN RAISE EXCEPTION 'Invalid payment method'; END IF;
  IF p_day IS NULL OR p_day > v_today THEN RAISE EXCEPTION 'A payment can’t be dated in the future.'; END IF;
  -- Lock order: the tournament row (the event's words and book), then the teams in id order, then the payment rows.
  SELECT w.category_id, w.item_id INTO v_cat, v_item FROM club_tournament_fee_word(p_tournament) w;
  v_book := club_tournament_ledger(p_tournament);
  PERFORM 1 FROM teams WHERE id = ANY(p_team_ids) AND tournament_id = p_tournament ORDER BY id FOR UPDATE;
  IF NOT FOUND OR (SELECT count(*) FROM teams WHERE id = ANY(p_team_ids) AND tournament_id = p_tournament) <> cardinality(p_team_ids)
    THEN RAISE EXCEPTION 'A selected team is not in this tournament'; END IF;
  FOR v_i IN 1..cardinality(p_team_ids) LOOP
    SELECT * INTO v_team FROM teams WHERE id = p_team_ids[v_i];
    v_amt := round(p_amounts[v_i], 2);
    IF v_amt IS NULL OR v_amt <= 0 THEN RAISE EXCEPTION 'Every payment amount must be positive'; END IF;
    IF EXISTS (SELECT 1 FROM rep_team_tournament_registrations l JOIN rep_teams r ON r.id = l.rep_team_id
               WHERE l.tournament_team_id = v_team.id AND l.org_id = v_t.org_id AND r.org_id = v_t.org_id) THEN
      RAISE EXCEPTION 'Our team has no entry fee';
    END IF;
    v_pid := gen_random_uuid();
    v_first := coalesce(v_first, v_pid);
    INSERT INTO tournament_team_payments(id, team_id, tournament_id, org_id, amount, paid_on, label, method, created_by)
    VALUES(v_pid, v_team.id, p_tournament, v_t.org_id, v_amt, p_day, 'Payment', p_method, p_actor);
    v_ids := v_ids || v_pid;
    v_total := v_total + v_amt;
  END LOOP;
  v_entry := club_fee_post(v_book, 'tournament_fee_receipt', v_first, p_day, tournament_payment_words(v_ids), v_total, p_actor, v_cat, v_item);
  UPDATE accounting_entries SET payment_method = p_method, notes = left(p_reference, 500) WHERE id = v_entry;
  UPDATE tournament_team_payments SET entry_id = v_entry WHERE id = ANY(v_ids);
  FOR v_i IN 1..cardinality(p_team_ids) LOOP
    PERFORM team_payments_refresh(p_team_ids[v_i], p_actor, 'live', p_day);
  END LOOP;
  RETURN v_first;
END $$;

-- ── 5. The link guard reads payments, not receipts ──────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.club_tournament_own_link_guard()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
DECLARE v_team public.teams%ROWTYPE; v_host uuid;
BEGIN
  SELECT * INTO v_team FROM teams
    WHERE id = CASE WHEN TG_OP = 'DELETE' THEN OLD.tournament_team_id ELSE NEW.tournament_team_id END
    FOR UPDATE;
  IF NOT FOUND THEN RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END; END IF;
  SELECT org_id INTO v_host FROM tournaments WHERE id = v_team.tournament_id;
  IF TG_OP = 'DELETE' THEN
    IF OLD.org_id = v_host AND EXISTS (SELECT 1 FROM rep_teams WHERE id = OLD.rep_team_id AND org_id = v_host)
       AND EXISTS (SELECT 1 FROM tournament_team_payments WHERE team_id = v_team.id AND status = 'posted') THEN
      RAISE EXCEPTION 'Undo this team''s paid status before removing its club-team link';
    END IF;
    RETURN OLD;
  END IF;
  IF NEW.org_id <> v_host OR NOT EXISTS (SELECT 1 FROM rep_teams WHERE id = NEW.rep_team_id AND org_id = v_host) THEN
    RAISE EXCEPTION 'The rep team and tournament must belong to the same club';
  END IF;
  IF EXISTS (SELECT 1 FROM tournament_team_payments p JOIN accounting_entries e ON e.id = p.entry_id
             WHERE p.team_id = v_team.id AND p.status = 'posted' AND e.status = 'posted') THEN
    RAISE EXCEPTION 'Undo the recorded entry fee before linking this as our team';
  END IF;
  RETURN NEW;
END $$;

-- ── 5b. A fee edit refreshes the figures of the teams that have payments ────────────────────────
-- deposit_paid is capped by the deposit fee, so correcting the deposit (or adding a deposit step, or switching the fee model)
-- would leave the cached deposit stale: a team that paid $100 against a corrected $100 deposit would still read "deposit due".
-- Figures only ('backfill' mode): a fee edit never changes anyone's status or sends anything.
CREATE OR REPLACE FUNCTION public.team_payments_fee_changed()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT DISTINCT p.team_id FROM tournament_team_payments p JOIN teams t ON t.id = p.team_id
    WHERE p.status = 'posted'
      AND (CASE WHEN TG_TABLE_NAME = 'tournaments' THEN t.tournament_id = NEW.id ELSE t.division_id = NEW.id END)
  LOOP
    PERFORM team_payments_refresh(r.team_id, NULL, 'backfill', NULL);
  END LOOP;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.team_payments_fee_changed() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS tournaments_fee_changed ON public.tournaments;
CREATE TRIGGER tournaments_fee_changed AFTER UPDATE OF deposit_amount, total_fee_amount, fee_schedule_mode ON public.tournaments
  FOR EACH ROW WHEN (OLD.deposit_amount IS DISTINCT FROM NEW.deposit_amount OR OLD.total_fee_amount IS DISTINCT FROM NEW.total_fee_amount
                     OR OLD.fee_schedule_mode IS DISTINCT FROM NEW.fee_schedule_mode)
  EXECUTE FUNCTION public.team_payments_fee_changed();
DROP TRIGGER IF EXISTS divisions_fee_changed ON public.divisions;
CREATE TRIGGER divisions_fee_changed AFTER UPDATE OF deposit_amount, total_fee_amount ON public.divisions
  FOR EACH ROW WHEN (OLD.deposit_amount IS DISTINCT FROM NEW.deposit_amount OR OLD.total_fee_amount IS DISTINCT FROM NEW.total_fee_amount)
  EXECUTE FUNCTION public.team_payments_fee_changed();

-- ── 6. Backfill: what is recorded today becomes rows ────────────────────────────────────────────
-- One row per posted receipt allocation (dated by its ledger line, linked to it), then one undated "Earlier payment" for the
-- rest of the figure (the baseline, or money marked paid on a plan with no book). Runs once, only into an empty table.
-- ⚠ BEFORE APPLYING TO PROD, run the pre-check in MANUAL_PROD_STEPS: a team whose posted allocations exceed its figure halts this.
DO $$
DECLARE v_bad integer; v_teams integer; r record;
BEGIN
  IF EXISTS (SELECT 1 FROM tournament_team_payments LIMIT 1) THEN RETURN; END IF;

  INSERT INTO tournament_team_payments(team_id, tournament_id, org_id, amount, paid_on, label, method, entry_id, status, created_by, created_at)
  SELECT a.team_id, t.tournament_id, tr.org_id, a.amount, e.entry_date, 'Payment', e.payment_method, e.id, 'posted', e.created_by, e.created_at
  FROM tournament_fee_receipt_allocations a
  JOIN tournament_fee_receipts rc ON rc.id = a.receipt_id
  JOIN accounting_entries e ON e.id = rc.entry_id AND e.status = 'posted'
  JOIN teams t ON t.id = a.team_id
  JOIN tournaments tr ON tr.id = t.tournament_id
  ORDER BY rc.ordinal;

  INSERT INTO tournament_team_payments(team_id, tournament_id, org_id, amount, paid_on, label, status, created_at)
  SELECT t.id, t.tournament_id, tr.org_id,
    greatest(coalesce(t.total_paid, 0), coalesce(t.deposit_paid, 0)) - coalesce((SELECT sum(p.amount) FROM tournament_team_payments p WHERE p.team_id = t.id AND p.status = 'posted'), 0),
    NULL, 'Earlier payment', 'posted', coalesce(t.registered_at, now())
  FROM teams t JOIN tournaments tr ON tr.id = t.tournament_id
  WHERE greatest(coalesce(t.total_paid, 0), coalesce(t.deposit_paid, 0)) - coalesce((SELECT sum(p.amount) FROM tournament_team_payments p WHERE p.team_id = t.id AND p.status = 'posted'), 0) > 0;

  -- Halt rather than guess: every team's rows must add up to the figure it carries today.
  SELECT count(*) INTO v_bad FROM teams t
  WHERE coalesce((SELECT sum(p.amount) FROM tournament_team_payments p WHERE p.team_id = t.id AND p.status = 'posted'), 0)
        <> greatest(coalesce(t.total_paid, 0), coalesce(t.deposit_paid, 0));
  IF v_bad > 0 THEN
    RAISE EXCEPTION 'Backfill halted: % team(s) whose payments would not add up to their paid figure', v_bad;
  END IF;

  -- The figures are rewritten from the rows (a deposit-only team's total now counts it; a deposit above the schedule's, or on a
  -- schedule with none, is rewritten too); the status and the stamp are left alone.
  v_teams := 0;
  FOR r IN SELECT DISTINCT team_id FROM tournament_team_payments LOOP
    PERFORM team_payments_refresh(r.team_id, NULL, 'backfill', NULL);
    v_teams := v_teams + 1;
  END LOOP;
  RAISE NOTICE 'Team payments backfilled for % team(s)', v_teams;
END $$;

